-- Run against inventory_db while ALL inventory writers are stopped.
-- This module has no automatic migration runner.
BEGIN;

CREATE TABLE IF NOT EXISTS inventory_operations (
    operation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    type VARCHAR(255) NOT NULL,
    completed BOOLEAN NOT NULL,
    CONSTRAINT uk_inventory_operation_order_type UNIQUE (order_id, type)
);

-- Keep completed keys for existing orders; one operation may have many book rows.
INSERT INTO inventory_operations (order_id, type, completed)
SELECT DISTINCT order_id, type, true
FROM inventory_transactions
WHERE order_id IS NOT NULL AND type IN ('ORDER_DEDUCT', 'ORDER_RESTORE')
ON CONFLICT (order_id, type) DO UPDATE SET completed = true;

COMMIT;

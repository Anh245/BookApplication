CREATE TABLE reading_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_subject VARCHAR(200) NOT NULL,
    book_id BIGINT NOT NULL,
    event_type VARCHAR(20) NOT NULL CHECK (event_type IN ('VIEW', 'FAVORITE', 'PURCHASE')),
    external_event_id VARCHAR(150) UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_reading_events_user_time ON reading_events(user_subject, created_at);

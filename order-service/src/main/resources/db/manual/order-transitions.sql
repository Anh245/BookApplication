-- PostgreSQL order_db; stop all old order-service writers before applying.
-- This module has no automatic migration runner.
BEGIN;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS version BIGINT NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS order_transitions (
    transition_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(order_id),
    source_status VARCHAR(255) NOT NULL,
    target_status VARCHAR(255) NOT NULL,
    state VARCHAR(255) NOT NULL,
    next_attempt_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT ck_order_transition_state CHECK (state IN ('PENDING', 'COMPLETED', 'REJECTED'))
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_order_transition_pending
    ON order_transitions (order_id) WHERE state = 'PENDING';
CREATE INDEX IF NOT EXISTS ix_order_transition_recovery ON order_transitions (state, next_attempt_at);
CREATE INDEX IF NOT EXISTS ix_order_transition_order ON order_transitions (order_id, state);
COMMIT;
